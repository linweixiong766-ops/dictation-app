function addPhonetics(filePath) {
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  let updated = 0;
  data.words.forEach(word => {
    if (!word.phonetic && phoneticMap[word.word.toLowerCase()]) {
      word.phonetic = phoneticMap[word.word.toLowerCase()];
      updated++;
    }
  });

  if (updated > 0) {
    fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf8');
    console.log(`Updated ${filePath}: ${updated} phonetics added`);
  } else {
    console.log(`No updates needed for ${filePath}`);
  }
}

