function addPhonetics(filePath) {
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  let updated = 0;
  let missing = [];

  data.words.forEach(word => {
    if (!word.phonetic || word.phonetic === '') {
      const lowerWord = word.word.toLowerCase();
      if (phoneticMap[lowerWord]) {
        word.phonetic = phoneticMap[lowerWord];
        updated++;
      } else {
        missing.push(word.word);
      }
    }
  });

  if (updated > 0) {
    fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf8');
    console.log(`Updated ${filePath}: ${updated} phonetics added`);
  }

  if (missing.length > 0) {
    console.log(`Still missing ${missing.length} phonetics in ${filePath}:`);
    console.log(missing.slice(0, 10).join(', ') + (missing.length > 10 ? '...' : ''));
  }

  return { updated, missing: missing.length };
}

// Process files
const files = [
  'public/data/en/grade3-spring.json',
  'public/data/en/grade4-spring.json',
  'public/data/en/grade5-fall.json'
];

let totalUpdated = 0;
let totalMissing = 0;

files.forEach(file => {
  const filePath = path.join(__dirname, file);
  if (fs.existsSync(filePath)) {
    const result = addPhonetics(filePath);
    totalUpdated += result.updated;
    totalMissing += result.missing;
  }
});

console.log(`\nTotal: ${totalUpdated} phonetics added, ${totalMissing} still missing`);
